"""Per-game Steam compatibility tool that wraps an installed Proton.

Why: real DLSS Frame Generation under Proton needs a working nvcuda.dll (Proton's
is an empty stub, forced with "nvcuda=b" after the user's overrides) and, for RTX
20/30, a patched DXVK-NVAPI (dlssg-open). Replacing those files inside Proton
would affect every game and be undone by Proton updates.

The wrapper runs the original Proton script with two optional edits, chosen per
game from its .dlss-swapper-linux.json ("proton_runtime"): a native nvcuda.dll in
the prefix with "nvcuda=n,b", and a different source for the nvapi64.dll Proton
copies into the prefix. Proton itself is not modified.
"""
from __future__ import annotations

import base64
import os
import re
import shutil
import time
from pathlib import Path

from . import fakecuda, vdf
from .steam import Game, library_folders, steam_running, SteamRunningError

TOOL_PREFIX = "dlss_swapper_"
LINK_NOTE = "nvcuda.dll.dlss-swapper-link"  # legacy name, same as the nvcuda note

WRAPPER = r'''#!/usr/bin/env python3
# Generated by dlss-swapper-linux: runs {base_name} unchanged except for what the
# game's .dlss-swapper-linux.json asks for:
#   * a native nvcuda.dll in the prefix (+ "nvcuda=n,b" instead of Proton's "nvcuda=b")
#   * a different nvapi64.dll copied into the prefix (patched DXVK-NVAPI)
import json, os, sys

BASE = {base!r}
TOOL = os.path.dirname(os.path.realpath(__file__))
LINK_NOTE = {link_note!r}


def wanted():
    game = os.environ.get("STEAM_COMPAT_INSTALL_PATH", "")
    try:
        with open(os.path.join(game, ".dlss-swapper-linux.json")) as f:
            state = json.load(f)
    except (OSError, ValueError):
        return {{}}
    w = dict(state.get("proton_runtime") or {{}})
    if not w.get("nvcuda") and any(v.get("options", {{}}).get("fake_cuda")
                                   for v in state.get("dlssg_sm86", {{}}).values()):
        w["nvcuda"] = "fake"
    return w


def place(kind, variant):
    """Put payload/<kind>-<variant>.dll into the prefix as <kind>.dll (keeps a note of a replaced symlink)."""
    src = os.path.join(TOOL, "payload", "%s-%s.dll" % (kind, variant))
    data = os.environ.get("STEAM_COMPAT_DATA_PATH", "")
    sys32 = os.path.join(data, "pfx", "drive_c", "windows", "system32")
    if not os.path.isfile(src) or not os.path.isdir(sys32):
        return
    with open(src, "rb") as f:
        payload = f.read()
    dst = os.path.join(sys32, kind + ".dll")
    try:
        if not os.path.islink(dst):
            with open(dst, "rb") as f:
                if f.read() == payload:
                    return
    except OSError:
        pass
    note = os.path.join(sys32, kind + ".dll.dlss-swapper-link")
    if os.path.islink(dst) and not os.path.exists(note):
        with open(note, "w") as f:
            f.write(os.readlink(dst))
    if os.path.lexists(dst):
        os.unlink(dst)
    with open(dst, "wb") as f:
        f.write(payload)


want = {{}}
try:
    want = wanted()
    if want.get("nvcuda"):
        place("nvcuda", want["nvcuda"])
    if want.get("nvapi64"):
        place("nvapi64", want["nvapi64"])   # Proton copies nvapi64 only on prefix setup
except Exception as e:  # never block the game launch
    sys.stderr.write("dlss-swapper wrapper: %s\\n" % e)

script = os.path.join(BASE, "proton")
with open(script) as f:
    src = f.read()
if want.get("nvcuda"):
    src = src.replace('g_session.dlloverrides["nvcuda"] = "b"', 'g_session.dlloverrides["nvcuda"] = "n,b"')
nvapi = want.get("nvapi64")
if nvapi and os.path.isfile(os.path.join(TOOL, "payload", "nvapi64-%s.dll" % nvapi)):
    src = src.replace('g_proton.arch_pe_dir("wine/nvapi", False) + "nvapi64.dll"',
                      repr(os.path.join(TOOL, "payload", "nvapi64-%s.dll" % nvapi)))
sys.argv[0] = script
sys.path.insert(0, BASE)  # Proton imports its own helpers (filelock.py, ...) from its directory
exec(compile(src, script, "exec"), {{"__name__": "__main__", "__file__": script}})
'''


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def find_protons(steam_root: Path) -> list[Path]:
    """Installed Valve Proton builds (directories with a 'proton' script)."""
    out = []
    for lib in library_folders(steam_root):
        common = lib / "steamapps/common"
        if common.is_dir():
            out += [p for p in common.iterdir() if p.name.startswith("Proton") and (p / "proton").is_file()]
    return sorted(out, key=lambda p: ("Experimental" not in p.name, p.name))


def _config_path(steam_root: Path) -> Path:
    return steam_root / "config/config.vdf"


def _mapping(data: dict, create: bool) -> dict | None:
    node = data
    for k in ("InstallConfigStore", "Software", "Valve", "Steam", "CompatToolMapping"):
        _, v = vdf.get_ci(node, k)
        if v is None:
            if not create:
                return None
            v = {}
            node[k] = v
        node = v
    return node


def get_tool(steam_root: Path, appid: str) -> str | None:
    f = _config_path(steam_root)
    if not f.is_file():
        return None
    m = _mapping(vdf.loads(f.read_text(errors="replace")), False) or {}
    entry = m.get(appid)
    return entry.get("name") if isinstance(entry, dict) else None


def set_tool(steam_root: Path, appid: str, name: str | None) -> None:
    """Map a game to a compatibility tool (None removes the per-game mapping)."""
    if steam_running():
        raise SteamRunningError("Закройте Steam: он перезапишет config.vdf при выходе.")
    f = _config_path(steam_root)
    data = vdf.loads(f.read_text(errors="replace"))
    m = _mapping(data, True)
    if name:
        m[appid] = {"name": name, "config": "", "priority": "250"}
    else:
        m.pop(appid, None)
    shutil.copy2(f, f.with_name(f.name + time.strftime(".bak-%Y%m%d-%H%M%S")))
    tmp = f.with_name(f.name + ".tmp")
    tmp.write_text(vdf.dumps(data))
    os.replace(tmp, f)


def extra_payloads() -> dict[str, dict[str, Path]]:
    """Runtime DLL sets other modules provide, e.g. {"dlssg_open": {"nvcuda": p, "nvapi64": p}}."""
    from . import dlssgopen  # local import: optional component
    return dlssgopen.payloads()


def install_tool(steam_root: Path, base: Path) -> str:
    """Create/refresh the wrapper tool for a Proton build; returns its internal name."""
    name = TOOL_PREFIX + _slug(base.name)
    d = steam_root / "compatibilitytools.d" / name
    d.mkdir(parents=True, exist_ok=True)
    display = f"{base.name} + DLSS FG (dlss-swapper)"
    (d / "compatibilitytool.vdf").write_text(vdf.dumps({"compatibilitytools": {"compat_tools": {name: {
        "install_path": ".", "display_name": display, "from_oslist": "windows", "to_oslist": "linux"}}}}))
    manifest = base / "toolmanifest.vdf"
    if manifest.is_file():
        shutil.copyfile(manifest, d / "toolmanifest.vdf")
    else:
        (d / "toolmanifest.vdf").write_text(vdf.dumps({"manifest": {
            "version": "2", "commandline": "/proton %verb%", "use_sessions": "1"}}))
    payload = d / "payload"
    payload.mkdir(exist_ok=True)
    (payload / "nvcuda-fake.dll").write_bytes(fakecuda.build())
    for variant, files in extra_payloads().items():
        for kind, src in files.items():
            shutil.copyfile(src, payload / f"{kind}-{variant}.dll")
    script = d / "proton"
    script.write_text(WRAPPER.format(base=str(base), base_name=base.name, link_note=LINK_NOTE))
    script.chmod(0o755)
    return name


def resolve_base(steam_root: Path, current: str | None) -> Path | None:
    """Pick the Proton build to wrap from the game's current tool name."""
    protons = find_protons(steam_root)
    if not protons:
        return None
    if current and current.startswith(TOOL_PREFIX):
        script = steam_root / "compatibilitytools.d" / current / "proton"
        m = re.search(r"^BASE = '(.*)'$", script.read_text(), re.M) if script.is_file() else None
        if m and Path(m.group(1)).is_dir():
            return Path(m.group(1))
    if current and "experimental" in current:
        exp = [p for p in protons if "Experimental" in p.name]
        if exp:
            return exp[0]
    numbered = [p for p in protons if re.search(r"\d", p.name)]
    if current and numbered and current != "proton_experimental":
        return sorted(numbered, key=lambda p: [int(x) for x in re.findall(r"\d+", p.name)])[-1]
    return protons[0]  # Experimental first, as Steam's default


def prefix_dir(game: Game) -> Path | None:
    """compatdata/<appid> of a Steam game or non-Steam shortcut."""
    if not game.steam_root or not game.appid:
        return None
    for lib in library_folders(game.steam_root):
        p = lib / "steamapps/compatdata" / game.appid
        if p.is_dir():
            return p
    return None


def place_in_prefix(game: Game, variant: str = "fake", kind: str = "nvcuda") -> Path | None:
    """Put an nvcuda.dll / nvapi64.dll variant into the game's prefix now (the wrapper also does it)."""
    pfx = prefix_dir(game)
    if not pfx:
        return None
    sys32 = pfx / "pfx/drive_c/windows/system32"
    if not sys32.is_dir():
        return None
    dst = sys32 / f"{kind}.dll"
    note = sys32 / f"{kind}.dll.dlss-swapper-link"
    if dst.is_symlink() and not note.exists():
        note.write_text(os.readlink(dst))
    if kind == "nvcuda" and variant == "fake":
        data = fakecuda.build()
    else:
        data = extra_payloads()[variant][kind].read_bytes()
    bak = sys32 / f"{kind}.dll.dlss-swapper-orig"
    if not dst.is_symlink() and dst.exists() and not bak.exists() and kind == "nvapi64":
        shutil.copy2(dst, bak)
    if dst.exists() and not dst.is_symlink() and dst.read_bytes() == data:
        return dst
    if dst.exists() or dst.is_symlink():
        dst.unlink()
    dst.write_bytes(data)
    return dst


def restore_prefix(game: Game) -> None:
    """Undo place_in_prefix / the wrapper: restore symlinks or original files."""
    pfx = prefix_dir(game)
    if not pfx:
        return
    sys32 = pfx / "pfx/drive_c/windows/system32"
    for kind in ("nvcuda", "nvapi64"):
        dst = sys32 / f"{kind}.dll"
        note = sys32 / f"{kind}.dll.dlss-swapper-link"
        bak = sys32 / f"{kind}.dll.dlss-swapper-orig"
        if note.is_file() and not dst.is_symlink():
            dst.unlink(missing_ok=True)
            os.symlink(note.read_text().strip(), dst)
        elif bak.is_file():
            os.replace(bak, dst)
        note.unlink(missing_ok=True)
        bak.unlink(missing_ok=True)
